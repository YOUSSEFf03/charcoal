export const DOC_LABELS: Record<DocLang, Record<DocLabelKey, string>> = {
  en: DOC_LABELS_EN,
  ar: DOC_LABELS_AR,
}

/**
 * Look up a fixed label. `vars` fills `{name}` placeholders (numbers are
 * rendered with Western digits). Unfilled placeholders are left as-is.
 */
export function t(lang: DocLang, key: DocLabelKey, vars?: Record<string, string | number>): string {
  const text = DOC_LABELS[lang][key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}
